export const DICTIONARY: Record<Lang, Record<TKey, string>> = { ht, en, es, fr, pt }

export function translate(lang: Lang, key: TKey, vars?: Record<string, string>) {
  let text = DICTIONARY[lang][key] ?? DICTIONARY.ht[key]
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, v)
  return text
}
